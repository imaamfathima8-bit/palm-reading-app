"""
llm_engine.py  (Task 04 - the "G" in RAG)
-----------------------------------------
Connects to the configured LLM and generates the structured palm report.

Specialisation mechanism: Retrieval-Augmented Generation.
    The model is a general-purpose LLM (Gemini, Groq-hosted Llama, or an
    OpenAI-compatible model). It becomes a "palmistry-specialised" model by
    receiving, in every request:
        1. a system prompt that fixes its role, rules and output format;
        2. the structured feature JSON for BOTH palms (never the images);
        3. the knowledge-base entries retrieved for those exact features.

Safeguards against unsupported claims (code-level, not just prompt-level):
    - The disclaimer is added by code, so it cannot be left out.
    - A detection-status table is generated by code from the JSON, so the
      record of what was and wasn't seen does not depend on the model.
    - The report is checked for all eight required sections.
    - API keys come only from environment variables via config.py.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from typing import Any

import config
from config import LLMSettings
from modules.knowledge_base import format_entries, retrieve_for_features

LINE_ORDER = ("heart", "head", "life", "fate")
# Gemini 3.x models "think" before answering; a full reading can take well
# over a minute. The limit only exists so a dead connection eventually shows
# an error instead of an endless spinner.
REQUEST_TIMEOUT_S = 300

REPORT_SECTIONS: tuple[str, ...] = (
    "1. Traditional interpretations of major lines and features",
    "2. Personality themes",
    "3. Career and professional-life themes",
    "4. Financial and prosperity themes",
    "5. Relationships and emotional themes",
    "6. Future-oriented narratives",
    "7. Left vs right palm comparison",
    "8. Uncertainty statements",
)

# ------------------------------------------------------------------
# Prompt templates
# ------------------------------------------------------------------
REPORT_SYSTEM_PROMPT = """You are a traditional palmistry narrator inside an educational ENTERTAINMENT application.
Palmistry is a cultural practice, not science. You never present it as fact.

You receive (a) feature data for a LEFT and a RIGHT palm, measured by a computer-vision
pipeline, and (b) entries from a curated palmistry knowledge base (KB).

STRICT RULES
1. Interpret ONLY with the KB entries provided. Cite the entry you used in square brackets,
   e.g. [KB:heart-long]. Do not use palmistry meanings that are not in the provided entries.
2. Describe ONLY features whose "status" is "detected" or "uncertain". For any line with
   "status": "not_detected", say it was "not clearly detected in the photo" and, at most, give its
   general traditional meaning from its overview entry. Never invent a length, shape, depth or
   position for it.
3. A line with "status": "uncertain" had weak image evidence. Always call it uncertain, never
   describe it as confirmed, and keep any interpretation of it brief and conditional.
4. Mark observations with "[Detected]" (facts from the feature data) and meanings with
   "[Interpretation]" (traditional symbolism), so observation and interpretation stay separate.
5. Use phrasing like "Palmistry traditionally associates ... with ...". Never say "you are" or
   "you will" as fact.
6. NEVER predict or comment on health, illness, lifespan, death, pregnancy, specific dates,
   amounts of money, or specific partners. NEVER give medical, financial, legal, career or
   relationship advice. If a theme has no supporting KB entry, say tradition offers no specific
   reading for it here.
7. Do NOT write your own disclaimer - the application adds one.

OUTPUT FORMAT
Markdown, about 600-900 words, with EXACTLY these level-2 headings in this order:
{sections}
- Section 6 must begin with the line: *Non-scientific, symbolic narrative - not a prediction.*
- Section 7 compares the two palms feature by feature, using only detected values.
- Section 8 lists every line that was not clearly detected or was uncertain, for each palm,
  and notes any warnings in the feature data.
"""

REPORT_USER_TEMPLATE = """LEFT PALM FEATURES (computer vision output):
```json
{left_json}
```

RIGHT PALM FEATURES (computer vision output):
```json
{right_json}
```

RETRIEVED KNOWLEDGE-BASE ENTRIES:
{kb_text}

Write the structured palm reading now, following every rule."""


# ------------------------------------------------------------------
# LLM client
# ------------------------------------------------------------------
class LLMError(Exception):
    """An LLM failure carrying a message that is safe to show the user."""


def _status_code(exc: Exception) -> int | None:
    """Pull an HTTP status code out of any provider's exception type."""
    for attr in ("status_code", "code", "status"):
        value = getattr(exc, attr, None)
        if isinstance(value, int):
            return value
    return None


def redact(text: str, settings: LLMSettings) -> str:
    """Remove the API key from any text before it is shown on screen."""
    if settings.api_key and len(settings.api_key) > 6:
        text = text.replace(settings.api_key, "[hidden API key]")
    return re.sub(r"(AIza|gsk_|sk-)[0-9A-Za-z_\-]{16,}", "[hidden API key]", text)


def friendly_error(exc: Exception, settings: LLMSettings) -> LLMError:
    """Translate SDK exceptions into actionable messages.

    WHY: a raw stack trace means nothing to an end user. Each provider
    raises different exception classes, but they all carry an HTTP status
    code, so we map on that.
    """
    code = _status_code(exc)
    text = str(exc).lower()
    if code in (401, 403) or "api key" in text or "api_key" in text:
        return LLMError(
            f"The {settings.provider} API key was rejected. Check the key in your .env file "
            "(no spaces or quote marks), or create a new key."
        )
    if "model name" in text or (code == 400 and "model" in text):
        return LLMError(
            f"The model name '{settings.model}' was rejected. Open .env and make the model line "
            "exactly: GEMINI_MODEL=gemini-3.6-flash (no quotes or spaces), then restart the app."
        )
    if code == 404 or "not found" in text:
        return LLMError(
            f"The model '{settings.model}' was not found or is not available to your key. "
            "Set a current model name in your .env file (for Gemini, e.g. gemini-3.6-flash)."
        )
    if code == 429 or "quota" in text or "rate limit" in text or "resource_exhausted" in text:
        return LLMError(
            "The free-tier rate limit was reached. Wait a minute and try again."
        )
    if code is not None and code >= 500:
        return LLMError(f"The {settings.provider} service is having problems ({code}). Try again shortly.")
    if "timeout" in text or "timed out" in text:
        return LLMError(f"The language model did not answer within {REQUEST_TIMEOUT_S // 60} minutes. "
                        "Check your internet connection and try again; if it keeps happening, "
                        "Google's service may be busy - try again later.")
    if "connect" in text or "network" in text or "resolve" in text:
        return LLMError("Could not reach the LLM service. Check your internet connection.")
    return LLMError(f"The language model request failed: {redact(str(exc), settings)[:400]}")


class LLMClient:
    """One small interface over three providers.

    WHY: report generation and chat call `generate()` and never need to know
    which provider is configured. Switching provider is a .env change only.

    messages: list of {"role": "user" | "assistant", "content": str}.
    """

    def __init__(self, settings: LLMSettings) -> None:
        self.settings = settings
        self._client: Any = None

    @property
    def label(self) -> str:
        """Human-readable provider/model, shown in the UI for documentation."""
        return f"{self.settings.provider} / {self.settings.model}"

    def _connect(self) -> Any:
        """Create the SDK client lazily, so the app starts even with no key."""
        if self._client is not None:
            return self._client
        s = self.settings
        # WHY a timeout: without one, a stalled network request leaves the
        # spinner running forever instead of showing an error.
        if s.provider == "gemini":
            from google import genai
            from google.genai import types
            self._client = genai.Client(api_key=s.api_key,
                                        http_options=types.HttpOptions(timeout=REQUEST_TIMEOUT_S * 1000))
        elif s.provider == "groq":
            from groq import Groq
            self._client = Groq(api_key=s.api_key, timeout=REQUEST_TIMEOUT_S)
        elif s.provider == "openai":
            from openai import OpenAI
            self._client = OpenAI(api_key=s.api_key, base_url=s.base_url, timeout=REQUEST_TIMEOUT_S)
        else:
            raise LLMError(f"Unsupported provider '{s.provider}'.")
        return self._client

    def generate(self, system: str, messages: list[dict[str, str]]) -> str:
        """Send a system prompt plus conversation and return the reply text."""
        try:
            client = self._connect()
            if self.settings.provider == "gemini":
                text = self._gemini(client, system, messages)
            else:
                text = self._chat_completions(client, system, messages)
        except LLMError:
            raise
        except ImportError as exc:
            raise LLMError(f"The SDK for {self.settings.provider} is not installed: {exc}. "
                           "Run: pip install -r requirements.txt") from exc
        except Exception as exc:  # noqa: BLE001 - every SDK has its own error classes
            raise friendly_error(exc, self.settings) from exc

        if not text or not text.strip():
            raise LLMError("The model returned an empty response (it may have been blocked "
                           "by a safety filter). Please try again.")
        return text.strip()

    def _gemini(self, client: Any, system: str, messages: list[dict[str, str]]) -> str:
        """Call Gemini through the google-genai SDK.

        WHY no temperature or token limit here: Google advises keeping
        Gemini 3.x models at their default temperature, and their internal
        "thinking" tokens count towards the output limit, so a low cap can
        cut the report off mid-sentence.
        WHY low thinking: the reading is built from a fixed knowledge base and
        needs little reasoning; low thinking answers several times faster.
        Models that do not support the setting are retried without it.
        """
        from google.genai import types

        contents = [
            types.Content(
                role="model" if m["role"] == "assistant" else "user",
                parts=[types.Part(text=m["content"])],
            )
            for m in messages
        ]
        fast = types.GenerateContentConfig(
            system_instruction=system,
            thinking_config=types.ThinkingConfig(thinking_level=types.ThinkingLevel.LOW),
        )
        try:
            response = client.models.generate_content(model=self.settings.model, contents=contents, config=fast)
        except Exception as exc:  # noqa: BLE001 - only retry when the thinking setting was rejected
            if _status_code(exc) != 400 or "think" not in str(exc).lower():
                raise
            response = client.models.generate_content(
                model=self.settings.model, contents=contents,
                config=types.GenerateContentConfig(system_instruction=system),
            )
        return response.text or ""

    def _chat_completions(self, client: Any, system: str, messages: list[dict[str, str]]) -> str:
        """Call Groq or OpenAI-compatible chat-completions APIs."""
        s = self.settings
        kwargs: dict[str, Any] = {
            "model": s.model,
            "messages": [{"role": "system", "content": system}, *messages],
            "temperature": s.temperature,
        }
        # Official OpenAI models use max_completion_tokens; Groq and most
        # OpenAI-compatible local servers still expect max_tokens.
        if s.provider == "openai" and not s.base_url:
            kwargs["max_completion_tokens"] = s.max_tokens
        else:
            kwargs["max_tokens"] = s.max_tokens
        response = client.chat.completions.create(**kwargs)
        return response.choices[0].message.content or ""


def get_client() -> LLMClient:
    """Build a client from the current .env settings."""
    return LLMClient(config.get_llm_settings())


# ------------------------------------------------------------------
# Report generation
# ------------------------------------------------------------------
@dataclass
class ReportResult:
    """The finished report plus everything needed to document how it was made."""

    markdown: str
    llm_text: str
    model_label: str
    kb_ids: list[str]
    system_prompt: str
    user_prompt: str
    warnings: list[str] = field(default_factory=list)


def features_for_prompt(features: dict) -> str:
    """Serialise one palm's features compactly for the prompt.

    WHY drop raw pixel measurements: they mean nothing to a reader and
    tempt the model to over-interpret numbers. Labels such as "long" or
    "curved" are what the knowledge base is keyed on.
    """
    trimmed = {k: v for k, v in features.items() if k != "shape_measurements"}
    trimmed["lines"] = {
        name: {k: v for k, v in line.items() if k not in ("length_ratio", "sagitta_ratio", "contrast")}
        for name, line in features.get("lines", {}).items()
    }
    return json.dumps(trimmed, indent=2)


def build_report_prompts(left: dict, right: dict) -> tuple[str, str, list[dict]]:
    """Retrieve KB entries for both palms and fill the prompt templates."""
    entries = retrieve_for_features(left, right)
    system = REPORT_SYSTEM_PROMPT.format(sections="\n".join(f"## {s}" for s in REPORT_SECTIONS))
    user = REPORT_USER_TEMPLATE.format(
        left_json=features_for_prompt(left),
        right_json=features_for_prompt(right),
        kb_text=format_entries(entries),
    )
    return system, user, entries


def _line_cell(line: dict) -> str:
    """One table cell describing a line's detection status."""
    if not line.get("detected"):
        return "⚠️ Not clearly detected"
    parts = [line.get(k) for k in ("length", "curvature", "depth") if line.get(k)]
    flag = "✅" if line.get("confidence", 0) >= 0.5 else "🟡 low confidence,"
    return f"{flag} {', '.join(parts)} (conf. {line.get('confidence', 0):.2f})"


def detection_table(left: dict, right: dict) -> str:
    """Markdown table of what computer vision actually detected.

    WHY generated by code: it is the ground truth the reader can check the
    LLM's text against, and it lists missing features even if the model
    forgets to.
    """
    rows = ["| Feature | Left palm | Right palm |", "|---|---|---|"]
    for name in LINE_ORDER:
        rows.append(f"| {name.title()} line | {_line_cell(left['lines'][name])} | {_line_cell(right['lines'][name])} |")
    rows.append(f"| Palm shape | {left.get('palm_shape', 'unknown')} | {right.get('palm_shape', 'unknown')} |")
    rows.append(f"| Element | {left.get('palm_element', 'unknown')} | {right.get('palm_element', 'unknown')} |")
    rows.append(f"| Detection method | {left.get('detection_method')} | {right.get('detection_method')} |")
    return "\n".join(rows)


# Phrases that would present palmistry as a factual prediction about health,
# lifespan, money or relationships. The prompt forbids them; this is a
# code-level second check because prompts alone cannot guarantee compliance.
UNSUPPORTED_CLAIMS = re.compile(
    r"\b(you will (die|live to|get (sick|ill|married|divorced)|become (rich|wealthy|poor)|marry|win)"
    r"|your (lifespan|life expectancy)|years to live|will (definitely|certainly) (happen|come true)"
    r"|(diagnos(e|is)|disease|illness|cancer) (is|will be) (indicated|shown|predicted))",
    re.IGNORECASE,
)


def unsupported_claims(text: str) -> list[str]:
    """Return short excerpts of any factual-prediction phrases in model output."""
    return [text[max(0, m.start() - 30): m.end() + 30].replace("\n", " ").strip()
            for m in UNSUPPORTED_CLAIMS.finditer(text)]


def missing_sections(text: str) -> list[str]:
    """Return the required section numbers the model left out."""
    lowered = text.lower()
    return [s for s in REPORT_SECTIONS if f"## {s.split('.')[0]}." not in lowered]


def assemble_report(llm_text: str, left: dict, right: dict, model_label: str, kb_ids: list[str]) -> str:
    """Wrap the LLM text with the disclaimer, provenance note and detection table."""
    return "\n\n".join([
        config.DISCLAIMER,
        f"*Interpretations below were generated by an LLM ({model_label}) using retrieval from a "
        "curated palmistry knowledge base. Lines marked [Detected] come from computer vision; "
        "lines marked [Interpretation] are traditional symbolism.*",
        llm_text,
        "---\n### Detection status (computer vision, generated by code - not by the LLM)",
        detection_table(left, right),
        f"<sub>Knowledge-base entries used: {', '.join(kb_ids)}</sub>",
        config.DISCLAIMER,
    ])


def generate_report(left: dict, right: dict, client: LLMClient | None = None) -> ReportResult:
    """Generate the full comparative report for both palms.

    Raises LLMError with a user-friendly message on any failure.
    """
    client = client or get_client()
    if (problem := config.check_llm_config(client.settings)):
        raise LLMError(problem)
    for side, palm in (("left", left), ("right", right)):
        # Only palms that passed hand detection may be interpreted - the LLM
        # must never write a reading for an image that was not validated.
        if palm.get("palm_side") != side or palm.get("detection_method") != "mediapipe":
            raise LLMError(f"The {side} palm has not been analysed successfully, so no reading "
                           "can be written. Upload a photo that passes all checks.")

    system, user, entries = build_report_prompts(left, right)
    llm_text = client.generate(system, [{"role": "user", "content": user}])
    kb_ids = [e["id"] for e in entries]

    warnings = []
    for excerpt in unsupported_claims(llm_text):
        warnings.append(f'The model wrote something that sounds like a factual prediction ("...{excerpt}..."). '
                        "Palmistry cannot predict this - treat it as symbolic only, or regenerate the reading.")
    if (missing := missing_sections(llm_text)):
        warnings.append("The model left out these sections: " + "; ".join(missing)
                        + ". You can regenerate the reading.")

    return ReportResult(
        markdown=assemble_report(llm_text, left, right, client.label, kb_ids),
        llm_text=llm_text,
        model_label=client.label,
        kb_ids=kb_ids,
        system_prompt=system,
        user_prompt=user,
        warnings=warnings,
    )
